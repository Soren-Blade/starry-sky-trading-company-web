/**
 * emoji → 图标名。
 *
 * 后端 `sstc.tools.icon` 与分类的 `icon_url` 存的是 emoji（🎬 / 📝 / 📦 …），
 * 那是**数据**不是代码，改起来要动数据库与后台录入习惯。因此在渲染端做一层
 * 映射：数据不动，界面统一成线性单色图标。
 *
 * 映射不到时调用方应回退成「原样显示这个 emoji」—— 数据里随时可能冒出新的
 * emoji（运营自己录一个 🚀），不能因为不在表里就渲染成空白。
 */
export const EMOJI_TO_ICON = {
    '🎬': 'video',
    '📺': 'video',
    '🎥': 'video',
    '📝': 'file',
    '📄': 'file',
    '📦': 'package',
    '🛠️': 'wrench',
    '🔧': 'wrench',
    '⭐': 'star',
    '🌟': 'star',
    '✨': 'star',
    '⚡': 'zap',
    '🔑': 'key',
    '🔒': 'key',
    '❤️': 'heart',
    '🛒': 'shopping-cart',
    '🛍️': 'shopping-bag',
    '🔍': 'search',
    '👤': 'user',
    '🎨': 'palette',
}

/** 查一个 emoji 对应的图标名；查不到返回空串 */
export function emojiToIconName(emoji) {
    if (typeof emoji !== 'string') return ''
    return EMOJI_TO_ICON[emoji.trim()] || ''
}
